-- V1
SELECT T.TNAME AS MISSING
  FROM (SELECT 'PSPNLFIELD' AS TNAME FROM DUAL UNION ALL
        SELECT 'PSPNLDEFN' FROM DUAL UNION ALL
        SELECT 'PSPNLGROUP' FROM DUAL UNION ALL
        SELECT 'PSPNLGRPDEFN' FROM DUAL UNION ALL
        SELECT 'PSRECFIELDDB' FROM DUAL UNION ALL
        SELECT 'PSRECDEFN' FROM DUAL UNION ALL
        SELECT 'PSDBFIELD' FROM DUAL UNION ALL
        SELECT 'PSXLATITEM' FROM DUAL UNION ALL
        SELECT 'PSSQLTEXTDEFN' FROM DUAL UNION ALL
        SELECT 'PSSTATUS' FROM DUAL) T
 WHERE NOT EXISTS (SELECT 1 FROM ALL_OBJECTS O
                    WHERE O.OBJECT_NAME = T.TNAME
                      AND O.OBJECT_TYPE IN ('TABLE', 'VIEW', 'SYNONYM'));

